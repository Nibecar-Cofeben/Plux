    function t(key, params = {}) {
      let keys = key.split('.');
      let value = i18n[currentLang];
      for (let k of keys) {
        if (value && value[k] !== undefined) value = value[k];
        else return key;
      }
      if (typeof value === 'string') {
        for (let p in params) value = value.replace(`{${p}}`, params[p]);
      }
      return value;
    }

